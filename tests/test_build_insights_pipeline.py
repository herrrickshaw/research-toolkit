def age_first_seen(world):
    con = duckdb.connect(str(world / "out" / "research_insights.duckdb"))
    con.execute("update docs set first_seen = current_date - 1")
    con.close()


def test_second_run_is_incremental(world, monkeypatch, capsys):
    run(monkeypatch)
    age_first_seen(world)
    first_claims = q(world, "select count(*) from claims")[0][0]
    capsys.readouterr()
    run(monkeypatch)
    out = capsys.readouterr().out
    assert "claims: scanned 0 new texts -> 0 claims" in out
    assert q(world, "select count(*) from claims")[0][0] == first_claims
    assert len(q(world, "select * from run_log")) == 2
    txt = (world / "out" / f"digest_{dt.date.today()}.md").read_text()
    assert "documents new since the previous run" in txt and "baseline" not in txt
    assert txt.splitlines()[2] == "0 documents new since the previous run."


def test_new_document_appears_in_next_digest(world, monkeypatch, capsys):
    run(monkeypatch)
    age_first_seen(world)
    con = duckdb.connect(str(world / "cat.duckdb"))
    f = world / "md" / "NEWDOC.md"
    f.write_text(body("dairy", 9, "extra new text"))
    con.execute("insert into documents(item_key,title,path,category,topic,filetype,year) values ('NEWDOC','Brand new dairy paper','papers/n.pdf','research','t','pdf','2024')")
    con.execute("insert into fulltext_md values ('NEWDOC','Brand new dairy paper', ?, 100, now(), 'ok')", [str(f)])
    con.close()
    run(monkeypatch)
    txt = (world / "out" / f"digest_{dt.date.today()}.md").read_text()
    assert "1 documents new since the previous run." in txt
    assert "Brand new dairy paper" in txt and txt.count("- **") == 1


