"""End-to-end tests of insights/build_insights.py (main + reports) on a synthetic catalog and corpus.

Everything is generated under tmp_path: the catalog duckdb, the markdown files, the memory notes and the output dir.
"""

import datetime as dt
import sys
from pathlib import Path

import duckdb
import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "insights"))
bi = pytest.importorskip("build_insights")

TOPICS = {
    "battery": "lithium anode cathode electrolyte separator cycle voltage charge discharge cell electrode graphite "
               "silicon dendrite capacity degradation pack module thermal runaway swelling formation calendar ageing",
    "solar": "photovoltaic wafer module inverter irradiance tracker string array cell perovskite silicon efficiency "
             "bifacial soiling curtailment feeder mounting rooftop utility tariff netmetering degradation panel",
    "dairy": "milk cattle herd fodder lactation cooperative pasteurisation yoghurt butter cheese whey calving "
             "udder veterinary silage heifer breed yield procurement chilling collection village dairy",
    "legal": "tribunal statute appellant respondent jurisdiction precedent injunction plaintiff arbitration clause "
             "tort damages counsel verdict bench petition affidavit remand costs ruling doctrine writ",
}
NOW = dt.datetime.now().replace(microsecond=0)


def body(topic, i, extra=""):
    words = TOPICS[topic].split()
    rot = words[i % len(words):] + words[:i % len(words)]
    # long enough (> 400 chars of head) and distinct per doc via the rotation + a doc-specific sentence
    return (f"Published 2024. {' '.join(rot)} {' '.join(rot[::-1])} {' '.join(rot[3:] + rot[:3])} "
            f"Study number {'x' * (i % 5)}{i} on {topic}. {extra}")


@pytest.fixture
def world(tmp_path, monkeypatch):
    md = tmp_path / "md"
    md.mkdir()
    docs, fts = [], []

    def add(key, title, text, category="research", path=None, year="2023", status="ok", converted=NOW):
        f = md / f"{key}.md"
        f.write_text(text)
        docs.append((key, title, path or f"papers/{key}.pdf", category, "topic", "pdf", year))
        fts.append((key, title, str(f), len(text), converted, status))

    n = 0
    for topic in TOPICS:
        for i in range(12):
            n += 1
            extra = ""
            if topic == "battery" and i == 0:
                extra = "The global lithium market was valued at USD 5 billion in 2030 estimates."
            if topic == "battery" and i == 1:
                extra = "The global lithium market was valued at USD 20 billion in 2030 estimates."
            if topic == "solar" and i == 0:
                extra = "The solar tracker market will grow at a CAGR of 9.5% over the period."
            add(f"LIT{n:03d}", f"Paper {topic} {i}", body(topic, i, extra))
    # exact copy of LIT001 under another key (larger chars -> still same text hash)
    add("DUP001", "Paper battery 0 copy", body("battery", 0, "The global lithium market was valued at USD 5 billion in 2030 estimates."),
        path="papers/copy.pdf")
    # near duplicate of LIT013 (solar 0): one extra word only
    add("NEAR01", "Paper solar 0 v2", body("solar", 0, "The solar tracker market will grow at a CAGR of 9.5% over the period.") + " addendum")
    # personal category is excluded entirely
    add("PERS01", "My diary", body("legal", 3), category="personal")
    # sensitive title / body are dropped from every output
    add("SENS01", "HDFC bank statement Jan", body("legal", 4))
    add("SENS02", "Quarterly notes", body("legal", 5, "Please quote your PAN ABCDE1234F"))
    # private folder: kept in stats but never shareable
    add("PRIV01", "Private folder paper", body("solar", 7), path="Documents/priv.pdf")
    # own output / machine backup
    for j in range(3):
        add(f"OWN{j}", f"Own note {j}", body("battery", 20 + j, "generated by Claude daily scan report"), category="backup",
            path=f"laptop_backup/own{j}.md")
    # tiny extraction (< 400 chars head) is kept out of clustering
    add("TINY01", "Tiny", "short", status="ok")
    # failed conversion is not loaded
    add("FAIL01", "Failed", body("dairy", 1), status="failed")

    cat = tmp_path / "cat.duckdb"
    con = duckdb.connect(str(cat))
    con.execute("create table documents(item_key varchar, title varchar, path varchar, category varchar, topic varchar, filetype varchar, year varchar, auto_topic varchar)")
    con.executemany("insert into documents(item_key,title,path,category,topic,filetype,year) values (?,?,?,?,?,?,?)",
                    [(k, t, p, c, tp, ft, y) for k, t, p, c, tp, ft, y in docs])
    con.execute("create table fulltext_md(item_key varchar, title varchar, md_path varchar, chars bigint, converted_at timestamp, status varchar)")
    con.executemany("insert into fulltext_md values (?,?,?,?,?,?)", fts)
    con.close()

    mem = tmp_path / "memory"
    mem.mkdir()
    (mem / "MEMORY.md").write_text("index")
    (mem / "battery_notes.md").write_text('---\nname: b\ndescription: "lithium cell anode cathode battery notes"\n---\nbody about lithium anode cathode')
    (mem / "api-key-note.md").write_text("---\ndescription: harmless\n---\nbody")
    (mem / "other.md").write_text("---\ndescription: contains a password hint\n---\nbody")

    out = tmp_path / "out"
    monkeypatch.setattr(bi, "OUT", out)
    monkeypatch.setattr(bi, "DB", out / "research_insights.duckdb")
    monkeypatch.setattr(bi, "CATALOG", cat)
    monkeypatch.setattr(bi, "MEMORY_DIR", mem)
    monkeypatch.setattr(bi, "N_CLUSTERS", 100)
    return tmp_path


def run(monkeypatch, *argv):
    monkeypatch.setattr(sys, "argv", ["build_insights.py", *argv])
    bi.main()


def q(world, sql, db="research_insights.duckdb"):
    con = duckdb.connect(str(world / "out" / db), read_only=True)
    try:
        return con.execute(sql).fetchall()
    finally:
        con.close()


